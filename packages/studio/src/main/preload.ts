// Every renderer call goes through here, so this is the one place where Electron's "Error invoking remote method" wrapping
// can be taken off before any screen turns the error into words.
function invoke<T>(request: StudioRequest): Promise<T> {
  return ipcRenderer.invoke("studio:invoke", request).catch((cause: unknown) => {
    throw unwrappedIpcError(cause)
  })
}

