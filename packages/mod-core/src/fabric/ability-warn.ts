/**
 * `target`: Fabric 1.21.1 (the default) is this file's own text and its edit to fabric.mod.json, exactly as before. A facade target (A 组) gets the packet and its
 * drawing through the facade, both classes mapped to its game version, and the two classes whose `register()` its common and client entries run (`entries`).
 */
export function compileAbilityWarn(value: z.input<typeof Input>, target: GenTarget = FABRIC_TARGET) {
  const input = Input.parse(value)
  const source = `src/main/java/${input.packageName.replaceAll(".", "/")}`
  const pack = input.packageName.replaceAll(".", "/")
  const mesh = input.mesh ? {modId:input.modId,target} : undefined
  const textures:Record<string,Uint8Array> = {}
  if (mesh) {
    const {pixels,width,height} = shapePixels({shape:"glint",side:16,points:4})
    textures[`src/main/resources/assets/${input.modId}/textures/fx/warn_glint.png`] = encodePng(pixels,width,height)
  }
  if (target.loader.facade)
    return {
      textures,
      files: {
        [`${source}/entity/${ABILITY_WARN.server}.java`]: target.version.rewriteJava(serverSource(input.packageName, input.modId, true, input.hollow, input.fields, input.own)),
        [`${source}/client/${ABILITY_WARN.client}.java`]: target.version.rewriteJava(clientSource(input.packageName, true, input.hollow, input.fields, mesh, input.ring)),
      } as Record<string, string>,
      classes: [`${pack}/entity/${ABILITY_WARN.server}.class`, `${pack}/client/${ABILITY_WARN.client}.class`],
      patch: {} as Record<string, (text: string) => string>,
      entries: { common: [`${input.packageName}.entity.${ABILITY_WARN.server}`], client: [`${input.packageName}.client.${ABILITY_WARN.client}`] },
    }
  const edit = (text: string, change: (value: Record<string, unknown>) => Record<string, unknown>) => {
    const edited = `${JSON.stringify(change(z.record(z.string(), z.unknown()).parse(JSON.parse(text))), null, 2)}\n`
    return text.includes("\r\n") ? edited.replaceAll("\n", "\r\n") : edited
  }
  return {
    textures,
    files: {
      [`${source}/entity/${ABILITY_WARN.server}.java`]: serverSource(input.packageName, input.modId, false, input.hollow, input.fields, input.own),
      [`${source}/client/${ABILITY_WARN.client}.java`]: clientSource(input.packageName, false, input.hollow, input.fields, mesh, input.ring),
    } as Record<string, string>,
    /** Paths inside the built jar that prove the warning went in. */
    classes: [`${pack}/entity/${ABILITY_WARN.server}.class`, `${pack}/client/${ABILITY_WARN.client}.class`],
    /** The packet is registered when the mod starts (both sides) and its receiver and its drawing when a player's game does. */
    patch: {
      "src/main/resources/fabric.mod.json": (text: string) =>
        edit(text, (metadata) => {
          const entrypoints = z.looseObject({ main: z.array(z.string()), client: z.array(z.string()).default([]) }).parse(metadata.entrypoints)
          return { ...metadata, entrypoints: { ...entrypoints, main: [...entrypoints.main, `${input.packageName}.entity.${ABILITY_WARN.server}`], client: [...entrypoints.client, `${input.packageName}.client.${ABILITY_WARN.client}`] } }
        }),
    } as Record<string, (text: string) => string>,
    /** Fabric names its entry points in fabric.mod.json (the patch above): nothing for the facade's entries. */
    entries: { common: [] as string[], client: [] as string[] },
  }
}
