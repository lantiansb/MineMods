/**
 * The warning before an area hit (Boss 能力 3) as what it adds to a generated mod. Only written when some hostile creature of the project has a hit with a warning,
 * so a project without any is untouched. The server decides every place; a player's game only draws.
 *
 * - a packet (`StudioWarn.Warn`, a `CustomPacketPayload` with its own `StreamCodec`) registered for the server-to-client direction: which creature (its entity id), the places
 *   (x, y, z each), the way it faced when they were decided, the hit's shape as its own numbers, how it looks, its colour and how many ticks are left before the hit.
 *   The same packet with no ticks left takes back every warning of that creature (its ability was cut short and the hit will not come), and with them at once the dust
 *   they already drew, which would otherwise linger for a second or more after.
 * - a receiver in the player's game (`StudioWarnClient`) that keeps the warnings still running and, every other tick of the client, draws each as dust on the ground: the outline the
 *   shape covers there (the same numbers the hit is checked with), an inner outline that grows from the middle to the edge as the hit comes, and for `pillar` a column of
 *   dust from the middle as high as the shape reaches.
 *
 * Every Minecraft and Fabric name used here is Mojang's own (Fabric Loom's official mappings), read with javap from the 1.21.1 jar and Fabric API.
 */

