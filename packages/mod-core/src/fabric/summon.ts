import { SUMMON_LIMITS } from "../boss-words"
import type { Summon } from "../entity-runtime"
import type { GenTarget } from "../platform/adapter"
import { PLATFORM_CLASS, PLATFORM_PACKAGE } from "../platform/facade"
import { FABRIC_TARGET } from "../platform/target"

/**
 * Calling a boss up (`summon` of a boss, 召唤): the class every summoning boss shares, and the line its creature's content class adds itself with.
 *
 * The player uses the item in the air, or on the altar when one is named; on the server the boss is made `ahead` blocks in front of the player (on the altar, the block
 * above it), at the first place up from there (at most `SUMMON_LIMITS.rise` blocks) where its body has room, facing the player, and comes into the world as one met
 * anywhere does: asleep until a player is near, so the one who called it wakes it. Nothing is called while one of its kind lives within `SUMMON_LIMITS.near` blocks.
 * The item, the altar and the creature are found by their registry names, so the class names nothing of any loader but how a use of an item or of a block reaches it:
 * Fabric API's callbacks, or the facade's (`StudioPlatform.onUseItem` / `onUseBlock`).
 */
export const SUMMON_CLASS = "StudioSummon"

const real = (value: number) => (Number.isInteger(value) ? value.toFixed(1) : String(value))
/** A name the way a document writes it (`minecraft:x`, or this project's own by identifier) as the game's registry name. */
const registryName = (modId: string, reference: string) => (reference.includes(":") ? reference : `${modId}:${reference}`)

/** The statement a summoning creature's content class runs in `register()`: its registry name and how it is called. */
export const summonCall = (modId: string, creature: string, summon: Summon) =>
  `${SUMMON_CLASS}.add("${modId}:${creature}", "${registryName(modId, summon.item)}", ${summon.block ? `"${registryName(modId, summon.block)}"` : "null"}, ${summon.consume}, ${Math.round(summon.cooldown * 20)}, ${real(summon.ahead)});`

/** The shared class (`entity` package's sibling: the mod's own package), written the same by every summoning creature. */
export function summonClass(packageName: string, target: GenTarget = FABRIC_TARGET, replacements: readonly string[] = []) {
  const facade = target.loader.facade
  const text = `package ${packageName};

${facade ? `import ${packageName}.${PLATFORM_PACKAGE}.${PLATFORM_CLASS};\n` : "import net.fabricmc.fabric.api.event.player.UseBlockCallback;\nimport net.fabricmc.fabric.api.event.player.UseItemCallback;\n"}import java.util.ArrayList;
import java.util.List;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.sounds.SoundSource;
import net.minecraft.util.Mth;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResult;
${facade ? "" : "import net.minecraft.world.InteractionResultHolder;\n"}import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.phys.BlockHitResult;
import net.minecraft.world.phys.Vec3;

/** Generated by MineMods Studio: how a player calls up this mod's bosses (an item used in the air, or on an altar). */
public final class ${SUMMON_CLASS} {
    /** One boss and how it is called: by registry names; \`block\` null for an item used in the air; \`cooldown\` in ticks. */
    private record Way(String creature, String item, String block, boolean consume, int cooldown, double ahead) {}

    private static final List<Way> WAYS = new ArrayList<>();
    private static boolean registered;

    private ${SUMMON_CLASS}() {}

    /** Called by each summoning creature's content class; the use of an item and of a block is listened to once. */
    public static void add(String creature, String item, String block, boolean consume, int cooldown, double ahead) {
        WAYS.add(new Way(creature, item, block, consume, cooldown, ahead));
        if (registered) return;
        registered = true;
${
  facade
    ? `        ${PLATFORM_CLASS}.onUseItem(${SUMMON_CLASS}::useItem);
        ${PLATFORM_CLASS}.onUseBlock(${SUMMON_CLASS}::useBlock);`
    : `        UseItemCallback.EVENT.register((player, level, hand) -> new InteractionResultHolder<>(useItem(player, level, hand), player.getItemInHand(hand)));
        UseBlockCallback.EVENT.register(${SUMMON_CLASS}::useBlock);`
}
    }

    private static boolean holds(ItemStack stack, String item) {
        return !stack.isEmpty() && BuiltInRegistries.ITEM.getKey(stack.getItem()).toString().equals(item);
    }

    /** An item used in the air: the first boss called by it with no altar. */
    public static InteractionResult useItem(Player player, Level level, InteractionHand hand) {
        ItemStack stack = player.getItemInHand(hand);
        for (Way way : WAYS) {
            if (way.block() != null || !holds(stack, way.item())) continue;
            if (level.isClientSide()) return InteractionResult.SUCCESS;
            Vec3 look = Vec3.directionFromRotation(0.0f, player.getYRot());
            BlockPos near = BlockPos.containing(player.getX() + look.x * way.ahead(), player.getY(), player.getZ() + look.z * way.ahead());
            return call((ServerLevel) level, player, hand, stack, way, near);
        }
        return InteractionResult.PASS;
    }

    /** An item used on a block: the first boss called by it on that altar (or, with no altar, by it alone). */
    public static InteractionResult useBlock(Player player, Level level, InteractionHand hand, BlockHitResult hit) {
        ItemStack stack = player.getItemInHand(hand);
        String block = BuiltInRegistries.BLOCK.getKey(level.getBlockState(hit.getBlockPos()).getBlock()).toString();
        for (Way way : WAYS) {
            if (way.block() == null || !way.block().equals(block) || !holds(stack, way.item())) continue;
            if (level.isClientSide()) return InteractionResult.SUCCESS;
            return call((ServerLevel) level, player, hand, stack, way, hit.getBlockPos().above());
        }
        return InteractionResult.PASS;
    }

    /** Makes the boss at the first place up from \`near\` that holds it; FAIL when it is on cooldown, already near or has no room. */
    private static InteractionResult call(ServerLevel world, Player player, InteractionHand hand, ItemStack stack, Way way, BlockPos near) {
        if (player.isSpectator()) return InteractionResult.PASS;
        Item item = stack.getItem();
        if (player.getCooldowns().isOnCooldown(item)) return InteractionResult.FAIL;
        EntityType<?> kind = BuiltInRegistries.ENTITY_TYPE.getOptional(ResourceLocation.tryParse(way.creature())).orElse(null);
        if (kind == null) return InteractionResult.FAIL;
        // One at a time: while one of its kind lives near the player, nothing more is called.
        if (!world.getEntities(kind, player.getBoundingBox().inflate(${SUMMON_LIMITS.near}.0), Entity::isAlive).isEmpty()) {
            ${replacements.includes("mute:summon_blocked") ? `if (${packageName}.entity.StudioBuiltin.audible(way.creature(), "summon_blocked")) ` : ""}world.playSound(null, player.blockPosition(), ${replacements.includes("summon_blocked") ? `${packageName}.entity.StudioBuiltin.sound(way.creature(), "summon_blocked", "minecraft:entity.item.break")` : "SoundEvents.ITEM_BREAK"}, SoundSource.PLAYERS, 0.4f, 0.6f);
            return InteractionResult.FAIL;
        }
        for (int up = 0; up <= ${SUMMON_LIMITS.rise}; up++) {
            Entity made = kind.create(world);
            if (made == null) return InteractionResult.FAIL;
            float yaw = Mth.wrapDegrees(player.getYRot() + 180.0f);
            made.moveTo(near.getX() + 0.5, near.getY() + up, near.getZ() + 0.5, yaw, 0.0f);
            made.setYHeadRot(yaw);
            if (!world.noCollision(made) || world.containsAnyLiquid(made.getBoundingBox())) continue;
            world.addFreshEntity(made);
            if (way.consume() && !player.getAbilities().instabuild) stack.shrink(1);
            if (way.cooldown() > 0) player.getCooldowns().addCooldown(item, way.cooldown());
            ${replacements.includes("mute:summon_success") ? `if (${packageName}.entity.StudioBuiltin.audible(way.creature(), "summon_success")) ` : ""}world.playSound(null, made.blockPosition(), ${replacements.includes("summon_success") ? `${packageName}.entity.StudioBuiltin.sound(way.creature(), "summon_success", "minecraft:entity.wither.spawn")` : "SoundEvents.WITHER_SPAWN"}, SoundSource.HOSTILE, 0.6f, 0.8f);
            return InteractionResult.SUCCESS;
        }
        return InteractionResult.FAIL;
    }
}
`
  // A facade target's version mapping is made with the creature's other classes (`platformCreature`), not here.
  return text
}
