/** On Fabric: Fabric API itself, with the same public members. */
function fabricCommon(root: string) {
  return `package ${root}.${GAMEPLAY_API.package};

import net.fabricmc.fabric.api.command.v2.CommandRegistrationCallback;
import net.fabricmc.fabric.api.entity.event.v1.ServerLivingEntityEvents;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents;
import net.fabricmc.fabric.api.event.player.UseBlockCallback;
import net.fabricmc.fabric.api.event.player.UseEntityCallback;
import net.fabricmc.fabric.api.event.player.UseItemCallback;
import net.fabricmc.fabric.api.networking.v1.PayloadTypeRegistry;
import net.fabricmc.fabric.api.networking.v1.PlayerLookup;
import net.fabricmc.fabric.api.networking.v1.ServerPlayConnectionEvents;
import net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking;
${COMMON_IMPORTS}
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.network.codec.StreamCodec;
import net.minecraft.network.protocol.common.custom.CustomPacketPayload;
import net.minecraft.world.InteractionResultHolder;
import net.minecraft.world.phys.Vec3;

${HEAD}
public final class ${GAMEPLAY_API.platform} {
    private ${GAMEPLAY_API.platform}() {}

${INTERFACES}

    /** After every server tick. */
    public static void onServerTick(Consumer<MinecraftServer> tick) { ServerTickEvents.END_SERVER_TICK.register(tick::accept); }

${LEVEL_TICK}

    /** Once a server has loaded its worlds, before its first tick. */
    public static void onServerStarted(Consumer<MinecraftServer> started) { ServerLifecycleEvents.SERVER_STARTED.register(started::accept); }

    /** A player has joined the server. */
    public static void onPlayerJoin(Consumer<ServerPlayer> join) { ServerPlayConnectionEvents.JOIN.register((handler, sender, server) -> join.accept(handler.player)); }

    /** A living entity has died, on the server, with what killed it. */
    public static void onEntityDeath(BiConsumer<LivingEntity, DamageSource> death) { ServerLivingEntityEvents.AFTER_DEATH.register(death::accept); }

    public static void onUseBlock(UseBlock handler) { UseBlockCallback.EVENT.register(handler::use); }

    public static void onUseItem(UseItem handler) {
        UseItemCallback.EVENT.register((player, level, hand) -> new InteractionResultHolder<>(handler.use(player, level, hand), player.getItemInHand(hand)));
    }

    public static void onUseEntity(UseEntity handler) { UseEntityCallback.EVENT.register((player, level, hand, entity, hit) -> handler.use(player, level, hand, entity)); }

    /** The server's commands, to add to (called whenever the server builds them). */
    public static void onCommands(Consumer<CommandDispatcher<CommandSourceStack>> commands) { CommandRegistrationCallback.EVENT.register((dispatcher, context, selection) -> commands.accept(dispatcher)); }

    /** Registers something of the game's registries in this mod's namespace (Registries.ITEM, Registries.BLOCK, ...). The supplier gives it once the game has registered it. */
    @SuppressWarnings("unchecked")
    public static <R, T extends R> Supplier<T> register(ResourceKey<? extends Registry<R>> registry, String name, Supplier<T> factory) {
        T value = Registry.register((Registry<R>) BuiltInRegistries.REGISTRY.get(registry.location()), ${GAMEPLAY_API.content}.id(name), factory.get());
        return () -> value;
    }

    /** A packet of the class P, sent by the server (s2c) or by a player's game (c2s). */
    public static final class Channel<P> {
        final CustomPacketPayload.Type<Packet<P>> type;
        final StreamCodec<FriendlyByteBuf, Packet<P>> codec;

        private Channel(String name, BiConsumer<P, FriendlyByteBuf> write, Function<FriendlyByteBuf, P> read) {
            type = new CustomPacketPayload.Type<>(${GAMEPLAY_API.content}.id("gameplay_" + name));
            codec = StreamCodec.of((buffer, packet) -> write.accept(packet.value(), buffer), buffer -> new Packet<>(this, read.apply(buffer)));
        }

        public void sendTo(ServerPlayer player, P value) {
            if (ServerPlayNetworking.canSend(player, type)) ServerPlayNetworking.send(player, new Packet<>(this, value));
        }

        public void sendTracking(Entity entity, P value) { PlayerLookup.tracking(entity).forEach(player -> sendTo(player, value)); }

        public void sendNear(ServerLevel level, double x, double y, double z, double radius, P value) {
            PlayerLookup.around(level, new Vec3(x, y, z), radius).forEach(player -> sendTo(player, value));
        }
    }

    /** The payload a channel's packet travels in. */
    public record Packet<P>(Channel<P> channel, P value) implements CustomPacketPayload {
        @Override public Type<? extends CustomPacketPayload> type() { return channel.type; }
    }

    /** A server-to-client packet; a player's game takes it with ${GAMEPLAY_API.client_platform}.onReceive. Each packet is a class of its own. */
    public static <P> Channel<P> s2c(String name, Class<P> type, BiConsumer<P, FriendlyByteBuf> write, Function<FriendlyByteBuf, P> read) {
        Channel<P> made = new Channel<>(name, write, read);
        PayloadTypeRegistry.playS2C().register(made.type, made.codec);
        return made;
    }

    /** A client-to-server packet: handler runs on the server's main thread with the player who sent it. A player's game sends it with ${GAMEPLAY_API.client_platform}.send. */
    public static <P> Channel<P> c2s(String name, Class<P> type, BiConsumer<P, FriendlyByteBuf> write, Function<FriendlyByteBuf, P> read, BiConsumer<ServerPlayer, P> handler) {
        Channel<P> made = new Channel<>(name, write, read);
        PayloadTypeRegistry.playC2S().register(made.type, made.codec);
        ServerPlayNetworking.registerGlobalReceiver(made.type, (packet, context) -> context.server().execute(() -> handler.accept(context.player(), packet.value())));
        return made;
    }
}
`
}

function fabricClient(root: string) {
  return `package ${root}.${GAMEPLAY_API.package};

import java.util.function.Consumer;
import net.fabricmc.fabric.api.client.event.lifecycle.v1.ClientTickEvents;
import net.fabricmc.fabric.api.client.keybinding.v1.KeyBindingHelper;
import net.fabricmc.fabric.api.client.networking.v1.ClientPlayNetworking;
import net.fabricmc.fabric.api.client.rendering.v1.HudRenderCallback;
import net.minecraft.client.KeyMapping;
import net.minecraft.client.gui.GuiGraphics;

/** Generated by MineMods Studio. What only a player's game does, the same on every loader. Name it only from client/ files; call each member from onInitializeClient. */
public final class ${GAMEPLAY_API.client_platform} {
    private ${GAMEPLAY_API.client_platform}() {}

    /** A key the player can rebind under Controls. */
    public static void keyMapping(KeyMapping mapping) { KeyBindingHelper.registerKeyBinding(mapping); }

    /** After every tick of the player's game (on the title screen too). */
    public static void onClientTick(Runnable tick) { ClientTickEvents.END_CLIENT_TICK.register(client -> tick.run()); }

    public interface Hud { void draw(GuiGraphics graphics, float partialTick); }

    /** Drawn over the game after the HUD. */
    public static void onHud(Hud hud) { HudRenderCallback.EVENT.register((graphics, counter) -> hud.draw(graphics, counter.getGameTimeDeltaPartialTick(true))); }

    /** What the player's game does with a server-to-client packet, on its main thread. */
    public static <P> void onReceive(${GAMEPLAY_API.platform}.Channel<P> channel, Consumer<P> handler) {
        ClientPlayNetworking.registerGlobalReceiver(channel.type, (packet, context) -> context.client().execute(() -> handler.accept(packet.value())));
    }

    /** Sends a client-to-server packet. */
    public static <P> void send(${GAMEPLAY_API.platform}.Channel<P> channel, P value) {
        if (ClientPlayNetworking.canSend(channel.type)) ClientPlayNetworking.send(new ${GAMEPLAY_API.platform}.Packet<>(channel, value));
    }
}
`
}

/** The two classes, by their path in the generated project, for one target. */
export function gameplayPlatformFiles(modId: string, target: GenTarget): Record<string, string> {
  const root = gameplayRoot(modId)
  const folder = `src/main/java/${root.replaceAll(".", "/")}/${GAMEPLAY_API.package}`
  const facade = target.loader.facade
  const files = {
    [`${folder}/${GAMEPLAY_API.platform}.java`]: facade ? facadeCommon(root, modPackage(modId)) : fabricCommon(root),
    [`${folder}/${GAMEPLAY_API.client_platform}.java`]: facade ? facadeClient(root, modPackage(modId)) : fabricClient(root),
  }
  return Object.fromEntries(Object.entries(files).map(([name, text]) => [name, target.version.rewriteJava(text)]))
}
