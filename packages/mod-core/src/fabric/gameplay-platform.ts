import { GAMEPLAY_API, gameplayRoot, modPackage } from "../gameplay"
import type { GenTarget } from "../platform/adapter"
import { CLIENT_PLATFORM_CLASS, PLATFORM_CLASS, PLATFORM_PACKAGE } from "../platform/facade"

/**
 * What gameplay code reaches the mod loader through (D 组): `ProjectPlatform` (both sides: server ticks, a server started,
 * a player joining, a death, a right-click on a block, an item or an entity, commands, registering, packets) and
 * `ProjectClient` (a player's game only: keys, client ticks, the HUD, packets in and out). The same public members on every
 * target, so code written against them compiles unchanged on Fabric, Forge and NeoForge:
 * - Forge and NeoForge: each member hands on to the generated facade (`StudioPlatform`, `StudioClientPlatform`), which is
 *   the only class that names the loader.
 * - Fabric: written with Fabric API itself (a Fabric mod is not generated through the facade), and only into a mod whose
 *   gameplay names one of the two classes, so every other Fabric mod is generated byte for byte as before.
 *
 * Every member is called once from `onInitialize` (`onInitializeClient` for `ProjectClient`): on Forge and NeoForge that runs
 * while the mod is constructed, before the loader takes its listeners, registers and packets.
 * A packet's name is put in the mod's namespace behind `gameplay_`, so it can never be one of Studio's own.
 */

/** The names of the two classes, as gameplay code writes them; a gameplay that names either on Fabric gets them generated. */
export const GAMEPLAY_PLATFORM_NAMES = [GAMEPLAY_API.platform, GAMEPLAY_API.client_platform] as const

const COMMON_IMPORTS = `import com.mojang.brigadier.CommandDispatcher;
import java.util.function.BiConsumer;
import java.util.function.Consumer;
import java.util.function.Function;
import java.util.function.Supplier;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.core.Registry;
import net.minecraft.network.FriendlyByteBuf;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.phys.BlockHitResult;`

const HEAD = `/**
 * Generated by MineMods Studio. What gameplay code reaches the mod loader through: the same members on Fabric, Forge and NeoForge,
 * so code that uses only these, ${GAMEPLAY_API.content} and the game's own classes is the same on every loader. Call each of them once,
 * from onInitialize: on Forge and NeoForge the loader takes listeners, registrations and packets only while the mod is being set up.
 */`

const INTERFACES = `    /** A right-click on a block, before the game's own: PASS lets the game go on, anything else is the result. Asked once per hand. */
    public interface UseBlock { InteractionResult use(Player player, Level level, InteractionHand hand, BlockHitResult hit); }

    /** A right-click with the item in a hand, before the game's own: PASS lets the game go on, anything else is the result. Asked once per hand. */
    public interface UseItem { InteractionResult use(Player player, Level level, InteractionHand hand); }

    /** A right-click on an entity, before the game's own: PASS lets the game go on, anything else is the result. Asked once per hand. */
    public interface UseEntity { InteractionResult use(Player player, Level level, InteractionHand hand, Entity entity); }`

const LEVEL_TICK = `    /** After every server tick, once for each of its worlds (after all of them have ticked). The place to make changes put off from elsewhere. */
    public static void onLevelTick(Consumer<ServerLevel> tick) {
        onServerTick(server -> {
            for (ServerLevel level : server.getAllLevels()) tick.accept(level);
        });
    }`

/** On Forge and NeoForge: every member hands on to the facade. */
function facadeCommon(root: string, mod: string) {
  return `package ${root}.${GAMEPLAY_API.package};

import ${mod}.${PLATFORM_PACKAGE}.${PLATFORM_CLASS};
${COMMON_IMPORTS}

${HEAD}
public final class ${GAMEPLAY_API.platform} {
    private ${GAMEPLAY_API.platform}() {}

${INTERFACES}

    /** After every server tick. */
    public static void onServerTick(Consumer<MinecraftServer> tick) { ${PLATFORM_CLASS}.onServerTick(tick); }

${LEVEL_TICK}

    /** Once a server has loaded its worlds, before its first tick. */
    public static void onServerStarted(Consumer<MinecraftServer> started) { ${PLATFORM_CLASS}.onServerStarted(started); }

    /** A player has joined the server. */
    public static void onPlayerJoin(Consumer<ServerPlayer> join) { ${PLATFORM_CLASS}.onPlayerJoin(join); }

    /** A living entity has died, on the server, with what killed it. */
    public static void onEntityDeath(BiConsumer<LivingEntity, DamageSource> death) { ${PLATFORM_CLASS}.onEntityDeath(death); }

    public static void onUseBlock(UseBlock handler) { ${PLATFORM_CLASS}.onUseBlock(handler::use); }

    public static void onUseItem(UseItem handler) { ${PLATFORM_CLASS}.onUseItem(handler::use); }

    public static void onUseEntity(UseEntity handler) { ${PLATFORM_CLASS}.onUseEntity(handler::use); }

    /** The server's commands, to add to (called whenever the server builds them). */
    public static void onCommands(Consumer<CommandDispatcher<CommandSourceStack>> commands) { ${PLATFORM_CLASS}.onCommands(commands); }

    /** Registers something of the game's registries in this mod's namespace (Registries.ITEM, Registries.BLOCK, ...). The supplier gives it once the game has registered it. */
    public static <R, T extends R> Supplier<T> register(ResourceKey<? extends Registry<R>> registry, String name, Supplier<T> factory) { return ${PLATFORM_CLASS}.register(registry, name, factory); }

    /** A packet of the class P, sent by the server (s2c) or by a player's game (c2s). */
    public static final class Channel<P> {
        final ${PLATFORM_CLASS}.Channel<P> channel;

        private Channel(${PLATFORM_CLASS}.Channel<P> channel) { this.channel = channel; }

        public void sendTo(ServerPlayer player, P value) { channel.sendTo(player, value); }

        public void sendTracking(Entity entity, P value) { channel.sendTracking(entity, value); }

        public void sendNear(ServerLevel level, double x, double y, double z, double radius, P value) { channel.sendNear(level, x, y, z, radius, value); }
    }

    /** A server-to-client packet; a player's game takes it with ${GAMEPLAY_API.client_platform}.onReceive. Each packet is a class of its own. */
    public static <P> Channel<P> s2c(String name, Class<P> type, BiConsumer<P, FriendlyByteBuf> write, Function<FriendlyByteBuf, P> read) {
        return new Channel<>(${PLATFORM_CLASS}.s2c("gameplay_" + name, type, write, read));
    }

    /** A client-to-server packet: handler runs on the server's main thread with the player who sent it. A player's game sends it with ${GAMEPLAY_API.client_platform}.send. */
    public static <P> Channel<P> c2s(String name, Class<P> type, BiConsumer<P, FriendlyByteBuf> write, Function<FriendlyByteBuf, P> read, BiConsumer<ServerPlayer, P> handler) {
        return new Channel<>(${PLATFORM_CLASS}.c2s("gameplay_" + name, type, write, read, handler));
    }
}
`
}

