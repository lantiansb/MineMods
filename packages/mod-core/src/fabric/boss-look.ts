import { z } from "zod"
import { BOSS_LOOK_LIMITS } from "../boss-words"
import type { GenTarget } from "../platform/adapter"
import { CLIENT_PLATFORM_CLASS, PLATFORM_CLASS, PLATFORM_PACKAGE } from "../platform/facade"
import { FABRIC_TARGET } from "../platform/target"

/**
 * Boss 能力 10: what a boss whose model changes with its phases adds to a generated mod, once for the whole mod (the creature's own share is `entity-boss.ts`'s
 * and its renderer's):
 * - a part that comes off (`StudioBossPart`): a plain entity of the mod's own type that keeps which creature's model and which bone it shows, falls where it came
 *   off, lies its ticks and is gone; never saved. A player's game draws it with the creature's own GeckoLib model, every bone hidden but that one and what hangs from
 *   it, moved so that the place it came off from is where it lies and turned as the creature was (`StudioBossPartRenderer`). The model is shared with the creature, so
 *   every bone is shown again after it is drawn.
 * - a glowing layer that fades (`StudioBossGlowLayer`): GeckoLib's own glow layer draws a glow mask at full brightness, always; this one draws each of the boss's glowing
 *   pictures at the brightness the creature says (its phase, and the time since it began), as the eyes of the game's own creatures are drawn (full bright, added on top),
 *   its colour scaled by the brightness. The colour is one int in GeckoLib 4.8.3 / 4.9.3 (1.21.1) and four floats in 4.8.4 (1.20.1): `VersionAdapter.boss.glowColour`.
 * Only written when some boss of the project needs it; each half only when it is needed. Every Minecraft and GeckoLib name is Mojang's own, read with javap from the three targets' class paths.
 */

const Input = z.strictObject({
  modId: z.string().regex(/^[a-z][a-z0-9_]{0,63}$/),
  packageName: z.string().regex(/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/),
  /** Some boss drops a part. */
  drop: z.boolean(),
  /** Some boss's phases glow. */
  glow: z.boolean(),
  /** Boss 能力 12: some boss's arena has a fog, so the glowing pictures are drawn with it lifted (`StudioArenaClient.fogFree`). */
  fogFree: z.boolean().default(false),
})

/** The classes a boss reaches this through, and the registry name of the parts' type. */
export const BOSS_LOOK_RUNTIME = { registry: "boss_part", entity: "StudioBossPart", table: "StudioBossParts", renderer: "StudioBossPartRenderer", client: "StudioBossPartsClient", glow: "StudioBossGlowLayer" } as const

function partSource(packageName: string, type: string) {
  const R = BOSS_LOOK_RUNTIME
  return `package ${packageName}.entity;

import java.util.ArrayList;
import java.util.List;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.network.syncher.EntityDataAccessor;
import net.minecraft.network.syncher.EntityDataSerializers;
import net.minecraft.network.syncher.SynchedEntityData;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.MoverType;
import net.minecraft.world.level.Level;
import net.minecraft.world.phys.Vec3;
import software.bernie.geckolib.animatable.GeoEntity;
import software.bernie.geckolib.animatable.instance.AnimatableInstanceCache;
import software.bernie.geckolib.animation.AnimatableManager;
import software.bernie.geckolib.util.GeckoLibUtil;

/**
 * Generated by MineMods Studio: a part that has come off a boss (Boss 能力 10). It shows one bone of its creature's model (and what hangs from it), falls where it came off,
 * lies its ticks and is gone. It hurts nobody, is in nobody's way and is never saved.
 */
public class ${R.entity} extends Entity implements GeoEntity {
    /** The most parts in the whole world at once; more are not made (the bone is gone from the boss all the same). */
    private static final int ALIVE = ${BOSS_LOOK_LIMITS.alive};
    private static final List<${R.entity}> PARTS = new ArrayList<>();
    // What every player's game is told: whose model (the creature's registry path), which bone, where on the model as built it came off from ({forward, up, left} in blocks) and how large its creature was.
    private static final EntityDataAccessor<String> CREATURE = SynchedEntityData.defineId(${R.entity}.class, EntityDataSerializers.STRING);
    private static final EntityDataAccessor<String> BONE = SynchedEntityData.defineId(${R.entity}.class, EntityDataSerializers.STRING);
    private static final EntityDataAccessor<Float> REST_FORWARD = SynchedEntityData.defineId(${R.entity}.class, EntityDataSerializers.FLOAT);
    private static final EntityDataAccessor<Float> REST_UP = SynchedEntityData.defineId(${R.entity}.class, EntityDataSerializers.FLOAT);
    private static final EntityDataAccessor<Float> REST_LEFT = SynchedEntityData.defineId(${R.entity}.class, EntityDataSerializers.FLOAT);
    private static final EntityDataAccessor<Float> SCALE = SynchedEntityData.defineId(${R.entity}.class, EntityDataSerializers.FLOAT);
    private final AnimatableInstanceCache animations = GeckoLibUtil.createInstanceCache(this);
    private int life;

    public ${R.entity}(EntityType<? extends ${R.entity}> type, Level world) { super(type, world); }

    /**
     * Makes bone \`bone\` of \`owner\` (whose model is \`creature\`) come off: it starts where it is on the creature now (\`forward\`, \`up\`, \`left\` of its feet in its own terms, blocks
     * at the size the model is built), is drawn about where that place is on the model as built (\`restForward\`…), turned as the creature's body is, and lies \`ticks\` ticks. Called on the server.
     */
    public static ${R.entity} drop(LivingEntity owner, String creature, String bone, int ticks, float forward, float up, float left, float restForward, float restUp, float restLeft) {
        if (!(owner.level() instanceof ServerLevel world)) return null;
        PARTS.removeIf(Entity::isRemoved);
        if (PARTS.size() >= ALIVE) return null;
        float scale = owner.getScale();
        float yaw = owner.yBodyRot;
        float turn = yaw * Mth.DEG_TO_RAD;
        ${R.entity} part = new ${R.entity}(${type}, world);
        part.moveTo(owner.getX() + (-forward * Mth.sin(turn) + left * Mth.cos(turn)) * scale, owner.getY() + up * scale, owner.getZ() + (forward * Mth.cos(turn) + left * Mth.sin(turn)) * scale, yaw, 0.0f);
        part.life = ticks;
        part.getEntityData().set(CREATURE, creature);
        part.getEntityData().set(BONE, bone);
        part.getEntityData().set(REST_FORWARD, restForward);
        part.getEntityData().set(REST_UP, restUp);
        part.getEntityData().set(REST_LEFT, restLeft);
        part.getEntityData().set(SCALE, scale);
        // It leaves with the creature's own motion and a little push up and to a side, then falls.
        part.setDeltaMovement(owner.getDeltaMovement().add((world.getRandom().nextDouble() - 0.5) * 0.12, 0.12, (world.getRandom().nextDouble() - 0.5) * 0.12));
        if (!world.addFreshEntity(part)) return null;
        PARTS.add(part);
        return part;
    }

    @Override protected void defineSynchedData(SynchedEntityData.Builder builder) {
        builder.define(CREATURE, "");
        builder.define(BONE, "");
        builder.define(REST_FORWARD, 0.0f);
        builder.define(REST_UP, 0.0f);
        builder.define(REST_LEFT, 0.0f);
        builder.define(SCALE, 1.0f);
    }

    public String creature() { return getEntityData().get(CREATURE); }

    public String bone() { return getEntityData().get(BONE); }

    /** Where on the model as built it came off from, {forward, up, left} in blocks, and how large its creature was. */
    public float[] rest() { return new float[] {getEntityData().get(REST_FORWARD), getEntityData().get(REST_UP), getEntityData().get(REST_LEFT)}; }

    public float partScale() { return getEntityData().get(SCALE); }

    @Override public void tick() {
        super.tick();
        // It falls, lands and slides to a stop against the blocks as anything the game moves does; the server ends it when its time is over.
        Vec3 motion = getDeltaMovement();
        if (!onGround()) motion = motion.add(0.0, -0.04, 0.0);
        setDeltaMovement(motion);
        move(MoverType.SELF, motion);
        motion = getDeltaMovement().scale(0.98);
        setDeltaMovement(onGround() ? motion.multiply(0.6, 0.0, 0.6) : motion);
        if (!level().isClientSide() && --life <= 0) discard();
    }

    // A part of a moment: it is not kept when the world is saved or a chunk unloads.
    @Override public boolean shouldBeSaved() { return false; }
    @Override public boolean isPickable() { return false; }
    @Override public boolean isPushable() { return false; }
    @Override protected void readAdditionalSaveData(CompoundTag nbt) {}
    @Override protected void addAdditionalSaveData(CompoundTag nbt) {}

    // Drawn with its creature's model and no motion of its own: the bone lies as the model is built.
    @Override public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {}

    @Override public AnimatableInstanceCache getAnimatableInstanceCache() { return animations; }
}
`
}

function rendererSource(packageName: string, modId: string) {
  const R = BOSS_LOOK_RUNTIME
  return `package ${packageName}.client;

import ${packageName}.entity.${R.entity};
import com.mojang.blaze3d.vertex.PoseStack;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import software.bernie.geckolib.cache.object.BakedGeoModel;
import software.bernie.geckolib.cache.object.GeoBone;
import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.renderer.GeoEntityRenderer;

/**
 * Generated by MineMods Studio: draws a part that has come off a boss with its creature's own model, every bone hidden but its own and what hangs from it, moved so that the
 * place it came off from is where it lies. The model is the creature's, shared by every one of its kind: every bone is shown again once the part is drawn.
 */
public final class ${R.renderer} extends GeoEntityRenderer<${R.entity}> {
    public ${R.renderer}(EntityRendererProvider.Context context) {
        super(context, new GeoModel<${R.entity}>() {
            @Override public ResourceLocation getModelResource(${R.entity} part) {
                return ResourceLocation.fromNamespaceAndPath(${JSON.stringify(modId)}, "geo/" + part.creature() + ".geo.json");
            }
            @Override public ResourceLocation getTextureResource(${R.entity} part) {
                return ResourceLocation.fromNamespaceAndPath(${JSON.stringify(modId)}, "textures/entity/" + part.creature() + ".png");
            }
            @Override public ResourceLocation getAnimationResource(${R.entity} part) {
                return ResourceLocation.fromNamespaceAndPath(${JSON.stringify(modId)}, "animations/" + part.creature() + ".animation.json");
            }
        });
        this.shadowRadius = 0.0f;
    }

    private static void hide(GeoBone bone, boolean hidden) {
        bone.setHidden(hidden);
        for (GeoBone child : bone.getChildBones()) hide(child, hidden);
    }

    @Override public void render(${R.entity} part, float yaw, float partialTick, PoseStack pose, MultiBufferSource buffers, int light) {
        if (part.creature().isEmpty()) return;
        BakedGeoModel model = getGeoModel().getBakedModel(getGeoModel().getModelResource(part));
        GeoBone kept = model == null ? null : model.getBone(part.bone()).orElse(null);
        if (kept == null) return;
        // Only the part: every bone hidden, the bones above it drawing nothing of their own but letting what hangs from them be drawn, and the part with all below it shown.
        for (GeoBone root : model.topLevelBones()) hide(root, true);
        for (GeoBone above = kept.getParent(); above != null; above = above.getParent()) above.setChildrenHidden(false);
        hide(kept, false);
        float[] rest = part.rest();
        float scale = part.partScale();
        float turn = part.getYRot() * Mth.DEG_TO_RAD;
        pose.pushPose();
        pose.translate(-(-rest[0] * Mth.sin(turn) + rest[2] * Mth.cos(turn)) * scale, -rest[1] * scale, -(rest[0] * Mth.cos(turn) + rest[2] * Mth.sin(turn)) * scale);
        pose.scale(scale, scale, scale);
        super.render(part, yaw, partialTick, pose, buffers, light);
        pose.popPose();
        for (GeoBone root : model.topLevelBones()) hide(root, false);
    }

    // GeckoLib turns what is not a living creature by nothing: the part is turned as its creature's body was when it came off.
    @Override protected void applyRotations(${R.entity} part, PoseStack pose, float age, float yaw, float partialTick, float nativeScale) {
        float turned = part.getYRot();
        super.applyRotations(part, pose, age, turned, partialTick, nativeScale);
    }
}
`
}

function glowSource(packageName: string, target: GenTarget, fogFree = false) {
  const R = BOSS_LOOK_RUNTIME
  return `package ${packageName}.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.Entity;
import software.bernie.geckolib.animatable.GeoEntity;
import software.bernie.geckolib.cache.object.BakedGeoModel;
import software.bernie.geckolib.renderer.GeoRenderer;
import software.bernie.geckolib.renderer.layer.GeoRenderLayer;

/**
 * Generated by MineMods Studio: a boss's glowing pictures (Boss 能力 10), each drawn over its model at full brightness, whatever the light around, as bright as the boss says now
 * (0 not at all, 1 fully): the game's own eyes are drawn so, added on top of what is under them, so a dimmer colour is a fainter glow.
 */
public class ${R.glow}<T extends Entity & GeoEntity> extends GeoRenderLayer<T> {
    /** How bright picture \`slot\` is now, 0 to 1. */
    public interface Glow<T> { float level(T creature, int slot, float partialTick); }

    private final ResourceLocation[] textures;
    private final Glow<T> glow;

    public ${R.glow}(GeoRenderer<T> renderer, ResourceLocation[] textures, Glow<T> glow) {
        super(renderer);
        this.textures = textures;
        this.glow = glow;
    }

    /** White at this brightness, opaque: what the picture's colour is multiplied by. */
    static int colour(float level) {
        int shade = (int) (Mth.clamp(level, 0.0f, 1.0f) * 255.0f);
        return 0xFF000000 | shade << 16 | shade << 8 | shade;
    }

    @Override public void render(PoseStack pose, T creature, BakedGeoModel model, RenderType type, MultiBufferSource buffers, VertexConsumer buffer, float partialTick, int light, int overlay) {
        for (int slot = 0; slot < textures.length; slot++) {
            float level = Mth.clamp(glow.level(creature, slot, partialTick), 0.0f, 1.0f);
            if (level < 0.004f) continue;
            RenderType glowing = ${fogFree ? "StudioArenaClient.fogFree(RenderType.eyes(textures[slot]))" : "RenderType.eyes(textures[slot])"};
            getRenderer().reRender(model, pose, buffers, creature, glowing, buffers.getBuffer(glowing), partialTick, 15728880, OverlayTexture.NO_OVERLAY, ${target.version.boss.glowColour("level")});
        }
    }
}
`
}

/**
 * `target`: Fabric 1.21.1 (the default) registers the parts' type and its renderer through two entry points named in fabric.mod.json (`patch`); a facade target through
 * the facade, run by the mod's entries (`entries`), every class mapped to its game version.
 */
export function compileBossLook(value: z.input<typeof Input>, target: GenTarget = FABRIC_TARGET) {
  const input = Input.parse(value)
  const R = BOSS_LOOK_RUNTIME
  const source = `src/main/java/${input.packageName.replaceAll(".", "/")}`
  const pack = input.packageName.replaceAll(".", "/")
  const language = input.drop ? { zh_cn: { [`entity.${input.modId}.${R.registry}`]: "掉下的部件" }, en_us: { [`entity.${input.modId}.${R.registry}`]: "Fallen part" } } : { zh_cn: {}, en_us: {} }
  const typeBuilder = `EntityType.Builder.<${R.entity}>of(${R.entity}::new, MobCategory.MISC)
            .sized(0.5f, 0.5f).noSave().noSummon().fireImmune().clientTrackingRange(8).updateInterval(2).build("${R.registry}")`
  const classes = [...(input.drop ? [`${pack}/entity/${R.entity}.class`, `${pack}/entity/${R.table}.class`, `${pack}/client/${R.renderer}.class`, `${pack}/client/${R.client}.class`] : []), ...(input.glow ? [`${pack}/client/${R.glow}.class`] : [])]
  if (target.loader.facade) {
    const written: Record<string, string> = {
      ...(input.drop
        ? {
            [`${source}/entity/${R.entity}.java`]: target.version.body.plainEntity(partSource(input.packageName, `${R.table}.TYPE.get()`)),
            [`${source}/entity/${R.table}.java`]: `package ${input.packageName}.entity;

import ${input.packageName}.${PLATFORM_PACKAGE}.${PLATFORM_CLASS};
import java.util.function.Supplier;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.MobCategory;

/** Generated by MineMods Studio: the one entity type every part that comes off a boss of this mod is (${target.manifest.id}), through the facade. */
public final class ${R.table} {
    public static final Supplier<EntityType<${R.entity}>> TYPE = ${PLATFORM_CLASS}.entity("${R.registry}",
        () -> ${typeBuilder});

    private ${R.table}() {}

    // Run by the mod's common entry while the mod is constructed: loading this class registers the type.
    public static void register() {}
}
`,
            [`${source}/client/${R.renderer}.java`]: target.version.body.rotations(rendererSource(input.packageName, input.modId)),
            [`${source}/client/${R.client}.java`]: `package ${input.packageName}.client;

import ${input.packageName}.entity.${R.table};
import ${input.packageName}.${PLATFORM_PACKAGE}.${CLIENT_PLATFORM_CLASS};

/** Generated by MineMods Studio: how a part that has come off a boss is drawn (${target.manifest.id}). */
public final class ${R.client} {
    public static void register() {
        ${CLIENT_PLATFORM_CLASS}.renderer(${R.table}.TYPE, ${R.renderer}::new);
    }
}
`,
          }
        : {}),
      ...(input.glow ? { [`${source}/client/${R.glow}.java`]: glowSource(input.packageName, target, input.fogFree) } : {}),
    }
    return {
      files: Object.fromEntries(Object.entries(written).map(([name, text]) => [name, target.version.rewriteJava(text)])),
      language,
      classes,
      patch: {} as Record<string, (text: string) => string>,
      entries: { common: input.drop ? [`${input.packageName}.entity.${R.table}`] : [], client: input.drop ? [`${input.packageName}.client.${R.client}`] : [] },
    }
  }
  const files: Record<string, string> = {
    ...(input.drop
      ? {
          [`${source}/entity/${R.entity}.java`]: partSource(input.packageName, `${R.table}.TYPE`),
          [`${source}/entity/${R.table}.java`]: `package ${input.packageName}.entity;

import net.fabricmc.api.ModInitializer;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.MobCategory;

/** Generated by MineMods Studio: the one entity type every part that comes off a boss of this mod is. */
public final class ${R.table} implements ModInitializer {
    public static final EntityType<${R.entity}> TYPE = Registry.register(
        BuiltInRegistries.ENTITY_TYPE, ResourceLocation.fromNamespaceAndPath(${JSON.stringify(input.modId)}, "${R.registry}"),
        ${typeBuilder});

    // Fabric builds a main entrypoint through its no-argument constructor, which must be public.
    public ${R.table}() {}

    // Loading this class registers the entity type; nothing else is needed at start.
    @Override public void onInitialize() {}
}
`,
          [`${source}/client/${R.renderer}.java`]: rendererSource(input.packageName, input.modId),
          [`${source}/client/${R.client}.java`]: `package ${input.packageName}.client;

import ${input.packageName}.entity.${R.table};
import net.fabricmc.api.ClientModInitializer;
import net.fabricmc.fabric.api.client.rendering.v1.EntityRendererRegistry;

/** Generated by MineMods Studio: how a part that has come off a boss is drawn. */
public final class ${R.client} implements ClientModInitializer {
    @Override public void onInitializeClient() {
        EntityRendererRegistry.register(${R.table}.TYPE, ${R.renderer}::new);
    }
}
`,
        }
      : {}),
    ...(input.glow ? { [`${source}/client/${R.glow}.java`]: glowSource(input.packageName, target, input.fogFree) } : {}),
  }
  const edit = (text: string, change: (value: Record<string, unknown>) => Record<string, unknown>) => {
    const edited = `${JSON.stringify(change(z.record(z.string(), z.unknown()).parse(JSON.parse(text))), null, 2)}\n`
    return text.includes("\r\n") ? edited.replaceAll("\n", "\r\n") : edited
  }
  return {
    files,
    language,
    classes,
    /** The parts' type is registered by a main entry point and drawn from a client one, both named in fabric.mod.json. */
    patch: (input.drop
      ? {
          "src/main/resources/fabric.mod.json": (text: string) =>
            edit(text, (metadata) => {
              const entrypoints = z.looseObject({ main: z.array(z.string()), client: z.array(z.string()).default([]) }).parse(metadata.entrypoints)
              return { ...metadata, entrypoints: { ...entrypoints, main: [...entrypoints.main, `${input.packageName}.entity.${R.table}`], client: [...entrypoints.client, `${input.packageName}.client.${R.client}`] } }
            }),
        }
      : {}) as Record<string, (text: string) => string>,
    entries: { common: [] as string[], client: [] as string[] },
  }
}
