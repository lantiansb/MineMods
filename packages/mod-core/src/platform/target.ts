import { DEFAULT_TARGET } from "../target/ids"
import type { LoaderKind } from "../target/manifest"
import { targetManifest } from "../target/manifests"
import type { GenTarget, LoaderAdapter } from "./adapter"
import { FABRIC_LOADER } from "./loader-fabric"
import { FORGE_LOADER } from "./loader-forge"
import { NEOFORGE_LOADER } from "./loader-neoforge"
import { versionAdapter } from "./version"

export type { GenTarget, LoaderAdapter, VersionAdapter, MinecraftLine, GeckoClass, NaturalSpawn, SpawnSource, PlatformInput } from "./adapter"

const LOADERS: Readonly<Record<LoaderKind, LoaderAdapter>> = { fabric: FABRIC_LOADER, forge: FORGE_LOADER, neoforge: NEOFORGE_LOADER }

export const loaderAdapter = (kind: LoaderKind) => LOADERS[kind]

/** The generation context of a target, by its manifest id: its manifest, its loader's adapter and its game version's. */
export function genTarget(id: string = DEFAULT_TARGET): GenTarget {
  const manifest = targetManifest(id)
  return { manifest, loader: loaderAdapter(manifest.loader.kind), version: versionAdapter(manifest.minecraft.version) }
}

/** What every generator defaults to: Fabric 1.21.1, generated exactly as before. */
export const FABRIC_TARGET: GenTarget = genTarget(DEFAULT_TARGET)

/** Whether a target is generated by the Fabric generator's own text, unchanged (as opposed to through the facade). */
export const isLegacyFabric = (target: GenTarget) => !target.loader.facade
