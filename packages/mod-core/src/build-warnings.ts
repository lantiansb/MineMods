export const BuildWarningSchema = z.strictObject({
  rule: z.string().max(40),
  about: z.string().nullable(),
  text: z.string(),
  fix: z.string(),
  refs: z.array(z.strictObject({
    kind: z.enum(FINDING_REF_KINDS),
    id: z.union([z.string(), z.number()]),
    title: z.string(),
  })).optional(),
  // Optional on read for receipts already on disk.
  severity: z.enum(["defect", "advice"]).optional(),
  about_id: z.string().optional(),
  emission: z.enum(Object.keys(EMISSION_FINDINGS) as (keyof typeof EMISSION_FINDINGS)[]).optional(),
})
export type BuildWarning = z.infer<typeof BuildWarningSchema>

export function buildWarningSeverity(warning: Pick<BuildWarning, "severity" | "emission" | "rule">): BuildWarningSeverity {
  if (warning.severity) return warning.severity
  if (warning.rule === "particle_emission" && warning.emission) return EMISSION_FINDINGS[warning.emission].severity
  return Object.hasOwn(BUILD_WARNING_RULES, warning.rule) ? BUILD_WARNING_RULES[warning.rule as keyof typeof BUILD_WARNING_RULES] : "advice"
}

/** Per occurrence, in the original order, for both the saved result and the external tool. */
export function buildWarnings(findings: readonly Finding[]): BuildWarning[] {
  return findings.filter((finding) => !finding.stops).map((finding) => ({
    rule: finding.rule,
    about: finding.about?.name ?? null,
    ...(finding.about ? { about_id: finding.about.id } : {}),
    text: finding.text,
    fix: finding.fix,
    ...(finding.refs?.length ? { refs: finding.refs } : {}),
    ...(finding.emission ? { emission: finding.emission } : {}),
    severity: buildWarningSeverity(finding),
  }))
}
