import { z } from "zod"
import { TRAIL_LIMITS } from "../ability-words"
import { abilityTick } from "../creature-abilities"
import type { TrailEvent } from "../ability-trails"

/**
 * What weapon trails (Boss 能力 11) add to a generated mod, the same on every loader: a record of one trail (`entity/StudioTrailSpec`, which a creature's class
 * lists as its `TRAILS`) and the class a player's game draws them with (`client/StudioTrails`). The server does nothing for a trail: every player's game
 * already knows which ability is showing and since when (the creature's synced ability value, `studioAbilityShown()`), and its own model is posed by GeckoLib.
 *
 * Nothing here hooks into a renderer: that is the platform layer's, which must, for a creature class C whose TRAILS is not empty, in C's GeoEntityRenderer:
 *  - keep one `new StudioTrails(C.TRAILS)` for the renderer;
 *  - in `preRender(...)` call `trails.track(model)` (GeckoLib then keeps the matrix of each part a trail follows: `GeoBone.setTrackingMatrices(true)`);
 *  - in `renderFinal(...)`, after super, with the pose stack as the entity renderer was handed it (at the creature, not turned), call
 *    `trails.frame(animatable, animatable.studioAbilityShown(), model, partialTick, poseStack, bufferSource)`.
 * GeckoLib 4.8.3 (Fabric 1.21.1) and 4.9.3 (NeoForge 1.21.1) and 4.8.4 (Forge 1.20.1) all have `BakedGeoModel.getBone(String)` and `GeoBone.getLocalSpaceMatrix()`,
 * `setTrackingMatrices`, `isTrackingMatrices` in the same package (`software.bernie.geckolib.cache.object`); only their `renderFinal` differs (4.8.4 passes the
 * colour as four floats, 4.8.3 and 4.9.3 as one int), which is the platform layer's to override. The one difference here is Minecraft's: a vertex is
 * `addVertex(matrix, x, y, z).setColor(r, g, b, a)` from 1.21 and `vertex(matrix, x, y, z).color(r, g, b, a).endVertex()` in 1.20.1 (`minecraft`).
 */

const Input = z.strictObject({
  packageName: z.string().regex(/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/),
  /** The Minecraft the classes are for: only how a vertex is written differs. */
  minecraft: z.enum(["1.21.1", "1.20.1"]).default("1.21.1"),
})
export type TrailCompileInput = z.input<typeof Input>

/** The classes a creature's class and the platform layer name. */
export const TRAIL_RUNTIME = { spec: "StudioTrailSpec", client: "StudioTrails" } as const

const single = (value: number) => `${Number(value.toFixed(5))}f`

/**
 * One trail of a creature as the Java its class lists: the ability (by its number), the ticks of that ability it is drawn from and until (`abilityTick`, the
 * rounding every moment of an ability has), the part, its far end from the part's pivot (`trailTip`'s `local`), its colour as 0xRRGGBB, its width and fade.
 */
export const trailSpec = (ability: number, event: TrailEvent, tip: readonly [number, number, number]) =>
  `new ${TRAIL_RUNTIME.spec}(${ability}, ${abilityTick(event.at)}, ${Math.max(abilityTick(event.at), abilityTick(event.until))}, ${JSON.stringify(event.bone)}, ${tip.map(single).join(", ")}, 0x${event.color.slice(1).toLowerCase()}, ${single(event.width)}, ${event.fade_ticks})`

export function compileTrails(value: TrailCompileInput) {
  const input = Input.parse(value)
  const source = `src/main/java/${input.packageName.replaceAll(".", "/")}`
  // How one corner of the ribbon is written: the only line that differs between the two Minecrafts.
  const vertex = input.minecraft === "1.20.1" ? "out.vertex(pose, x, y, z).color(red, green, blue, alpha).endVertex();" : "out.addVertex(pose, x, y, z).setColor(red, green, blue, alpha);"
  return {
    files: {
      [`${source}/entity/${TRAIL_RUNTIME.spec}.java`]: `package ${input.packageName}.entity;

/**
 * Generated by MineMods Studio: one weapon trail of a creature. While ability number \`ability\` runs, from its tick \`from\` to its tick \`until\`, a player's game keeps where the far end of
 * the model's part \`bone\` is and draws a ribbon through those places: \`tipX/Y/Z\` is that end from the part's pivot in blocks, in GeckoLib's axes (the corner of the part's own cubes furthest
 * from its pivot), \`color\` is 0xRRGGBB, \`width\` the ribbon's width in blocks, and each stretch of it fades out over \`fade\` ticks after the end passed it.
 */
public record ${TRAIL_RUNTIME.spec}(int ability, int from, int until, String bone, float tipX, float tipY, float tipZ, int color, float width, int fade) {
}
`,
      [`${source}/client/${TRAIL_RUNTIME.client}.java`]: `package ${input.packageName}.client;

import ${input.packageName}.entity.${TRAIL_RUNTIME.spec};
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import java.util.ArrayDeque;
import java.util.Iterator;
import java.util.Map;
import java.util.Optional;
import java.util.WeakHashMap;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.phys.Vec3;
import org.joml.Matrix4f;
import org.joml.Vector3f;
import software.bernie.geckolib.cache.object.BakedGeoModel;
import software.bernie.geckolib.cache.object.GeoBone;

/**
 * Generated by MineMods Studio: the weapon trails of one kind of creature, as a player's game draws them. One of these a renderer.
 * Every frame, after GeckoLib has drawn the creature, it reads where the far end of each trail's part is (the part's matrix as GeckoLib posed it, at the creature's place
 * between ticks), keeps it while the trail's ability is between the trail's ticks, and draws what it kept as a ribbon facing the camera, glowing in the trail's colour,
 * each stretch thinning and fading over the trail's fade after the end passed it. When the ability is cut short the server stops showing it and nothing more is kept.
 * It is the platform layer that calls it (see track and frame); nothing here hooks into a loader.
 */
public final class ${TRAIL_RUNTIME.client} {
    /** The most places kept for one trail of one creature. */
    private static final int MOST = ${TRAIL_LIMITS.points};
    /** Places nearer than this to the last one kept are not kept again (blocks): a part held still leaves one place, not one a frame. */
    private static final float APART = 0.01f;
    /** How solid the ribbon is where the end has just passed. */
    private static final float SOLID = 0.85f;

    private final ${TRAIL_RUNTIME.spec}[] trails;
    /** Per creature on screen: what it was last seen showing and since when, and the places kept for each trail. Let go of with the creature. */
    private final Map<Entity, Run> runs = new WeakHashMap<>();

    public ${TRAIL_RUNTIME.client}(${TRAIL_RUNTIME.spec}[] trails) {
        this.trails = trails;
    }

    private static final class Run {
        int shown;
        float start;
        final ArrayDeque<float[]>[] kept;

        @SuppressWarnings("unchecked")
        Run(int count) {
            kept = new ArrayDeque[count];
            for (int index = 0; index < count; index++) kept[index] = new ArrayDeque<>();
        }
    }

    /** Before the creature is drawn (the renderer's preRender): GeckoLib is to keep the matrix of every part a trail follows, so it can be read after. */
    public void track(BakedGeoModel model) {
        for (${TRAIL_RUNTIME.spec} trail : trails) model.getBone(trail.bone()).ifPresent(bone -> bone.setTrackingMatrices(true));
    }

    /**
     * After the creature is drawn, every frame (the renderer's renderFinal, the pose stack as the entity renderer was handed it: at the creature, not turned).
     * \`shown\` is the creature's studioAbilityShown(): 0 for no ability, else a count that changes on every start above the ability's number plus one in the low byte.
     */
    public void frame(Entity entity, int shown, BakedGeoModel model, float partialTick, PoseStack poseStack, MultiBufferSource buffers) {
        Run run = runs.computeIfAbsent(entity, key -> new Run(trails.length));
        float now = entity.tickCount + partialTick;
        // An ability starts in this game when it is first seen showing: the moment GeckoLib starts its motion too.
        if (shown != run.shown) {
            run.shown = shown;
            run.start = now;
        }
        int ability = (shown & 255) - 1;
        float tick = now - run.start;
        Vec3 origin = entity.getPosition(partialTick);
        for (int index = 0; index < trails.length; index++) {
            ${TRAIL_RUNTIME.spec} trail = trails[index];
            ArrayDeque<float[]> kept = run.kept[index];
            while (!kept.isEmpty() && now - kept.peekFirst()[3] > trail.fade()) kept.pollFirst();
            if (shown != 0 && ability == trail.ability() && tick >= trail.from() && tick <= trail.until()) keep(trail, kept, model, origin, now);
            draw(trail, kept, now, origin, poseStack, buffers);
        }
    }

    /** Where the far end of the trail's part is now, kept when it has moved. A part GeckoLib has not been keeping the matrix of is told to, and read from the next frame on. */
    private static void keep(${TRAIL_RUNTIME.spec} trail, ArrayDeque<float[]> kept, BakedGeoModel model, Vec3 origin, float now) {
        Optional<GeoBone> found = model.getBone(trail.bone());
        if (found.isEmpty()) return;
        GeoBone bone = found.get();
        if (!bone.isTrackingMatrices()) {
            bone.setTrackingMatrices(true);
            return;
        }
        Vector3f tip = bone.getLocalSpaceMatrix().transformPosition(new Vector3f(trail.tipX(), trail.tipY(), trail.tipZ()));
        float x = (float) (origin.x + tip.x());
        float y = (float) (origin.y + tip.y());
        float z = (float) (origin.z + tip.z());
        float[] last = kept.peekLast();
        if (last != null && Math.abs(last[0] - x) + Math.abs(last[1] - y) + Math.abs(last[2] - z) < APART) return;
        kept.addLast(new float[] {x, y, z, now});
        if (kept.size() > MOST) kept.pollFirst();
    }

    /** The ribbon through the kept places, from the oldest to the newest, each place as wide and as solid as what is left of its fade. */
    private static void draw(${TRAIL_RUNTIME.spec} trail, ArrayDeque<float[]> kept, float now, Vec3 origin, PoseStack poseStack, MultiBufferSource buffers) {
        int count = kept.size();
        if (count < 2) return;
        float[][] places = new float[count][];
        Iterator<float[]> each = kept.iterator();
        for (int index = 0; index < count; index++) places[index] = each.next();
        Vec3 eye = Minecraft.getInstance().gameRenderer.getMainCamera().getPosition();
        // Each place's sideways: across the way the ribbon runs there and the way the camera looks at it, so the ribbon is seen flat on.
        float[][] sides = new float[count][];
        for (int index = 0; index < count; index++) {
            float[] before = places[Math.max(0, index - 1)];
            float[] after = places[Math.min(count - 1, index + 1)];
            Vector3f along = new Vector3f(after[0] - before[0], after[1] - before[1], after[2] - before[2]);
            Vector3f look = new Vector3f((float) (places[index][0] - eye.x), (float) (places[index][1] - eye.y), (float) (places[index][2] - eye.z));
            Vector3f side = along.cross(look);
            float length = side.length();
            float left = Math.max(0.0f, 1.0f - (now - places[index][3]) / trail.fade());
            float half = length < 1.0e-6f ? 0.0f : trail.width() * 0.5f * left / length;
            sides[index] = new float[] {side.x() * half, side.y() * half, side.z() * half, left};
        }
        float red = ((trail.color() >> 16) & 255) / 255.0f;
        float green = ((trail.color() >> 8) & 255) / 255.0f;
        float blue = (trail.color() & 255) / 255.0f;
        VertexConsumer out = buffers.getBuffer(RenderType.lightning());
        Matrix4f pose = poseStack.last().pose();
        for (int index = 0; index + 1 < count; index++) {
            float[] a = places[index];
            float[] b = places[index + 1];
            float[] sa = sides[index];
            float[] sb = sides[index + 1];
            float ax = (float) (a[0] - origin.x), ay = (float) (a[1] - origin.y), az = (float) (a[2] - origin.z);
            float bx = (float) (b[0] - origin.x), by = (float) (b[1] - origin.y), bz = (float) (b[2] - origin.z);
            // Both faces of the quad: the ribbon is seen from whichever side the camera is on.
            for (int face = 0; face < 2; face++) {
                float flip = face == 0 ? 1.0f : -1.0f;
                corner(out, pose, ax - sa[0] * flip, ay - sa[1] * flip, az - sa[2] * flip, red, green, blue, SOLID * sa[3]);
                corner(out, pose, ax + sa[0] * flip, ay + sa[1] * flip, az + sa[2] * flip, red, green, blue, SOLID * sa[3]);
                corner(out, pose, bx + sb[0] * flip, by + sb[1] * flip, bz + sb[2] * flip, red, green, blue, SOLID * sb[3]);
                corner(out, pose, bx - sb[0] * flip, by - sb[1] * flip, bz - sb[2] * flip, red, green, blue, SOLID * sb[3]);
            }
        }
    }

    private static void corner(VertexConsumer out, Matrix4f pose, float x, float y, float z, float red, float green, float blue, float alpha) {
        ${vertex}
    }
}
`,
    } as Record<string, string>,
  }
}
