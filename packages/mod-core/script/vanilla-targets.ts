import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { unzipSync } from "fflate"
import { CONVENTION_ITEM_TAGS, MINECRAFT_ITEM_TAGS, VANILLA_ITEM_NAMES } from "../src/fabric/content-vanilla"

/**
 * Writes `src/platform/vanilla-targets-data.ts`: what of the vanilla items and item tags a project may name (the lists of
 * `fabric/content-vanilla.ts`: Minecraft 1.21.1 and Fabric's convention tags) a facade target does not have, read out of
 * that target's own game and loader jars, so a recipe or a tool's repair that names one is refused for that target in
 * plain words instead of being dropped by the game when it loads.
 *
 *   bun script/vanilla-targets.ts <1.20.1 client-extra jar (game resources)> <NeoForge 1.21.1 jar>
 *
 * - Forge 1.20.1: an item is there when the game has its item model (`assets/minecraft/models/item/<id>.json`); a tag
 *   when its file is under `data/minecraft/tags/items`. Forge 1.20.1 has no `c:` tags.
 * - NeoForge 1.21.1: the same game, so the same items and `minecraft:` tags; the `c:` tags are NeoForge's own
 *   (`data/c/tags/item` in its jar).
 */
const [clientExtra1201, neoforgeJar] = process.argv.slice(2)
if (!clientExtra1201 || !neoforgeJar) throw new Error("Usage: bun script/vanilla-targets.ts <client-extra-1.20.1 jar> <neoforge-21.1 jar>")

const tagsIn = (jar: string, prefix: string) =>
  new Set(
    Object.keys(unzipSync(new Uint8Array(readFileSync(jar)), { filter: (file) => file.name.startsWith(prefix) && file.name.endsWith(".json") })).map((name) => name.slice(prefix.length, -".json".length)),
  )

// Every item of the game has its item model (the language file is no proof: 1.20.1's smithing templates share one name).
const models1201 = tagsIn(clientExtra1201, "assets/minecraft/models/item/")
const items1201 = Object.keys(VANILLA_ITEM_NAMES).filter((id) => !models1201.has(id)).sort()
const tags1201 = tagsIn(clientExtra1201, "data/minecraft/tags/items/")
const minecraftTags1201 = [...MINECRAFT_ITEM_TAGS].filter((tag) => !tags1201.has(tag)).sort()
const neoforgeTags = tagsIn(neoforgeJar, "data/c/tags/item/")
const conventionNeoforge = [...CONVENTION_ITEM_TAGS].filter((tag) => !neoforgeTags.has(tag)).sort()

const list = (values: readonly string[]) => `[${values.map((value) => JSON.stringify(value)).join(", ")}]`
const text = `/**
 * Generated by script/vanilla-targets.ts from the targets' own jars: what of \`fabric/content-vanilla.ts\` (Minecraft 1.21.1,
 * Fabric's convention tags) each facade target does not have. Do not edit by hand.
 */

// prettier-ignore
export const MISSING_ON_TARGET: Readonly<Record<string, { readonly items: readonly string[]; readonly minecraftTags: readonly string[]; readonly conventionTags: readonly string[] | "all" }>> = {
  "forge-1.20.1": {
    items: ${list(items1201)},
    minecraftTags: ${list(minecraftTags1201)},
    conventionTags: "all",
  },
  "neoforge-1.21.1": {
    items: [],
    minecraftTags: [],
    conventionTags: ${list(conventionNeoforge)},
  },
}
`
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/platform/vanilla-targets-data.ts")
writeFileSync(out, text)
console.log(`forge-1.20.1: ${items1201.length} items, ${minecraftTags1201.length} minecraft tags missing; neoforge-1.21.1: ${conventionNeoforge.length} c tags missing. Written to ${out}`)
