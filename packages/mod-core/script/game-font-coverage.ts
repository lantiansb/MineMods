import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { unzipSync } from "fflate"

/**
 * Writes `src/game-font-coverage.ts`: which characters the game's default font can draw, for each game version a target runs on, read off
 * the game's own font files as the game reads them (`default.json`: the space advances, the bitmaps of `include/default`, then unifont from
 * the asset index, its Japanese variant left out). A character none of them has is drawn as the empty box. Planes beyond the BMP are read
 * too: that is where the rare Chinese characters (Extension B and later) are, and where 1.20.1 and 1.21.1 differ.
 *
 *   bun packages/mod-core/script/game-font-coverage.ts <1.21.1 client jar> <1.20.1 client assets jar> <assets folder with indexes/ and objects/>
 *
 * The same files as `book-font-widths.ts` reads. Nothing of the game is copied into the repository: only which code points are covered.
 */
const [modern, legacy, assets] = process.argv.slice(2)
if (!modern || !legacy || !assets) throw new Error("Usage: bun packages/mod-core/script/game-font-coverage.ts <1.21.1 client jar> <1.20.1 client jar> <assets folder>")

type Provider = { type: string; file?: string; chars?: string[]; advances?: Record<string, number>; hex_file?: string; filter?: Record<string, boolean> }
const lenient = (text: string) => JSON.parse(text.replace(/,(\s*[\]}])/g, "$1")) as { providers: Provider[] }
const decoder = new TextDecoder()

async function covered(jar: string, index: string) {
  const files = unzipSync(await readFile(jar), { filter: (entry) => entry.name.startsWith("assets/minecraft/font/") })
  const objects = (JSON.parse(await readFile(path.join(assets, "indexes", `${index}.json`), "utf8")) as { objects: Record<string, { hash: string }> }).objects
  const object = (name: string) => readFile(path.join(assets, "objects", objects[name]!.hash.slice(0, 2), objects[name]!.hash))
  const found = new Set<number>()
  for (const provider of lenient(decoder.decode(files["assets/minecraft/font/include/space.json"]!)).providers)
    for (const char of Object.keys(provider.advances ?? {})) found.add(char.codePointAt(0)!)
  for (const provider of lenient(decoder.decode(files["assets/minecraft/font/include/default.json"]!)).providers) {
    if (provider.type !== "bitmap") continue
    for (const row of provider.chars ?? []) for (const char of row) if (char.codePointAt(0)) found.add(char.codePointAt(0)!)
  }
  for (const provider of lenient(decoder.decode(await object("minecraft/font/include/unifont.json"))).providers.filter((value) => !value.filter?.jp)) {
    if (!provider.hex_file) continue
    const zip = unzipSync(await object(`minecraft/${provider.hex_file.replace("minecraft:", "")}`))
    for (const [name, bytes] of Object.entries(zip)) {
      if (!name.endsWith(".hex")) continue
      for (const line of decoder.decode(bytes).split(/\r?\n/)) {
        const [code, data] = line.split(":")
        if (code && data) found.add(parseInt(code, 16))
      }
    }
  }
  return found
}

/** Covered code points as runs: base-36 "gap.length" pieces, each gap counted from the end of the run before. */
function encode(found: Set<number>) {
  const codes = [...found].sort((a, b) => a - b)
  const runs: [number, number][] = []
  for (const code of codes) {
    const last = runs.at(-1)
    if (last && last[0] + last[1] === code) last[1] += 1
    else runs.push([code, 1])
  }
  let end = 0
  return runs.map(([start, length]) => {
    const piece = `${(start - end).toString(36)}.${length.toString(36)}`
    end = start + length
    return piece
  }).join(",")
}

const sets = { "1.21.1": await covered(modern, "17"), "1.20.1": await covered(legacy, "5") }
const out = path.join(import.meta.dir, "../src/game-font-coverage.ts")
await writeFile(out, `// Generated by script/game-font-coverage.ts from the game's own font files. Do not edit.
/** The characters the default font draws, per game version, as base-36 "gap.length" runs of code points (gaps from the end of the run before). */
export const FONT_COVERAGE = ${JSON.stringify(Object.fromEntries(Object.entries(sets).map(([version, found]) => [version, encode(found)])), null, 2)} as const
`)
for (const [version, found] of Object.entries(sets)) console.log(version, found.size, "characters;", "U+24FE4", found.has(0x24fe4), "U+20000", found.has(0x20000), "中", found.has(0x4e2d))
